        <tbody>
            <tr class="bg-red-50 border-b"><td class="p-2 font-semibold">Urgensi &amp; Panik</td><td class="p-2">Menciptakan tekanan waktu</td><td class="p-2 italic">'Akun kamu diblokir dalam 1 jam!'</td></tr>
