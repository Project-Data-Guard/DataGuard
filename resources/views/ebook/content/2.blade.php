{{-- PAGE 4: Bab 3 - Modus 1 & 2 --}}
<div class="book-page">
    <h2 class="text-2xl font-extrabold text-red-700 mb-4 border-b-2 border-red-100 pb-2">3. Modus Penipuan yang Sering Menyasar Remaja</h2>
    <div class="mb-5">
        <h3 class="font-bold text-gray-900 mb-2">Modus 1: Giveaway &amp; Hadiah Palsu</h3>
        <p class="text-sm text-gray-700 mb-2">Penipu membuat akun atau konten yang menawarkan hadiah fantastis (iPhone, uang tunai, tiket konser) melalui Instagram, TikTok, atau WhatsApp. Setelah korban tertarik, mereka diminta mengisi data pribadi, membayar 'biaya pajak hadiah', atau mengklik link berbahaya.</p>
        <div class="bg-yellow-50 border border-yellow-200 rounded-xl p-3 text-sm"><strong class="text-yellow-800">Ciri khasnya:</strong> <span class="text-yellow-700">Hadiah terlalu bagus untuk jadi kenyataan. Akun pengirim baru dibuat atau jumlah followers sedikit. Diminta DM terlebih dahulu untuk 'klaim hadiah'. Ada syarat membayar biaya admin/pajak.</span></div>
    </div>
    <div>
        <h3 class="font-bold text-gray-900 mb-2">Modus 2: Jual Beli Akun Game &amp; Item Langka</h3>
        <p class="text-sm text-gray-700 mb-2">Penipu menawarkan akun game populer (Mobile Legends, Free Fire, PUBG) atau item langka dengan harga jauh di bawah harga pasar melalui grup Facebook, WhatsApp, atau Discord. Setelah pembeli mentransfer uang, penjual menghilang atau melakukan 'hackback'.</p>
        <div class="bg-yellow-50 border border-yellow-200 rounded-xl p-3 text-sm"><strong class="text-yellow-800">Ciri khasnya:</strong> <span class="text-yellow-700">Harga jauh di bawah harga pasar. Tidak mau menggunakan rekening bersama (rekber) resmi. Profil penjual baru atau tanpa testimoni nyata. Akun bisa direbut kembali setelah transaksi (hackback).</span></div>
    </div>
</div>

{{-- PAGE 5: Modus 3 & 4 --}}
<div class="book-page">
    <div class="mb-5">
        <h3 class="font-bold text-gray-900 mb-2">Modus 3: APK Berbahaya via WhatsApp &amp; Telegram</h3>
        <p class="text-sm text-gray-700 mb-2">Penipu mengirimkan file APK (aplikasi Android) berkedok berbagai hal menarik: surat tilang polisi, undangan pernikahan digital, paket ekspedisi, update aplikasi resmi, hingga konten dewasa. Jika diinstal, APK tersebut mengambil alih perangkat dan menguras saldo mobile banking atau dompet digital korban.</p>
        <div class="bg-red-50 border border-red-200 rounded-xl p-3 text-sm"><strong class="text-red-800">Ciri khasnya:</strong> <span class="text-red-700">File berekstensi .APK dikirim dari nomor tidak dikenal. Isi pesan mengandung urgensi ('segera buka', 'konfirmasi sekarang'). Aplikasi meminta izin akses berlebihan saat diinstal (SMS, kontak, kamera). <strong>Ingat: Jangan pernah menginstal APK dari luar Play Store atau App Store!</strong></span></div>
    </div>
    <div>
        <h3 class="font-bold text-gray-900 mb-2">Modus 4: Phishing Link di Media Sosial &amp; WhatsApp</h3>
        <p class="text-sm text-gray-700 mb-2">Penipu mengirim link yang tampilannya mirip situs resmi (bank, marketplace, platform game) melalui DM Instagram, grup WhatsApp, atau Telegram. Korban diminta login di situs palsu tersebut, dan data login langsung dicuri. Modus ini juga sering menyasar akun dengan banyak followers untuk diambil alih.</p>
        <div class="bg-yellow-50 border border-yellow-200 rounded-xl p-3 text-sm"><strong class="text-yellow-800">Ciri khasnya:</strong> <span class="text-yellow-700">URL sedikit berbeda dari aslinya (misal: 'tokopedia-promo.com' bukan 'tokopedia.com'). Tampilan situs sangat mirip dengan yang asli. Meminta login ulang atau verifikasi akun mendadak.</span></div>
    </div>
</div>

{{-- PAGE 6: Modus 5, 6, 7 --}}
<div class="book-page">
    <div class="mb-4">
        <h3 class="font-bold text-gray-900 mb-1">Modus 5: Lowongan Kerja &amp; Freelance Palsu</h3>
        <p class="text-sm text-gray-700 mb-2">Ini adalah modus paling banyak dilaporkan sepanjang 2024. Penipu menawarkan pekerjaan freelance atau part-time dengan gaji menggiurkan melalui WhatsApp. Korban diminta membayar deposit atau memberikan data rekening untuk 'pencarian gaji' yang tidak pernah datang.</p>
        <div class="bg-yellow-50 border border-yellow-200 rounded-xl p-2 text-xs"><strong class="text-yellow-800">Ciri:</strong> <span class="text-yellow-700">Gaji tidak masuk akal untuk pekerjaan mudah. Direkrut tanpa proses seleksi. Diminta bayar deposit atau beli 'starter kit'.</span></div>
    </div>
    <div class="mb-4">
        <h3 class="font-bold text-gray-900 mb-1">Modus 6: Jastip &amp; Tiket Konser/Event Palsu</h3>
        <p class="text-sm text-gray-700 mb-2">Menjelang konser artis populer, penipu menjual tiket atau membuka jasa titip (jastip) palsu di media sosial dengan harga menggiurkan. Setelah korban mentransfer uang, penjual menghilang.</p>
        <div class="bg-yellow-50 border border-yellow-200 rounded-xl p-2 text-xs"><strong class="text-yellow-800">Ciri:</strong> <span class="text-yellow-700">Harga jauh lebih murah dari harga resmi. Tidak ada rekening bersama atau escrow. Menolak video call untuk verifikasi.</span></div>
    </div>
    <div>
        <h3 class="font-bold text-gray-900 mb-1">Modus 7: Investasi &amp; Trading Crypto Palsu</h3>
        <p class="text-sm text-gray-700 mb-2">Penipu menyebarkan tautan di media sosial lalu mengarahkan korban ke grup WhatsApp berkedok 'komunitas investasi'. Seseorang yang mengaku 'mentor' memberikan edukasi palsu dengan iming-iming keuntungan besar dari crypto atau trading saham.</p>
        <div class="bg-yellow-50 border border-yellow-200 rounded-xl p-2 text-xs"><strong class="text-yellow-800">Ciri:</strong> <span class="text-yellow-700">Menjanjikan keuntungan pasti dalam waktu singkat. Platform investasi tidak terdaftar di OJK. Diminta transfer ke rekening pribadi.</span></div>
    </div>
</div>

{{-- PAGE 7: Modus 8 & Bab 4 --}}
<div class="book-page">
    <div class="mb-5">
        <h3 class="font-bold text-gray-900 mb-2">Modus 8: Smishing (SMS Palsu) &amp; Vishing (Telepon Palsu)</h3>
        <p class="text-sm text-gray-700 mb-2">Smishing adalah phishing via SMS/WhatsApp. Penipu berpura-pura jadi pihak bank, kurir paket, atau instansi pemerintah. Vishing adalah penipuan via telepon. Penipu mengaku dari bank dan meminta OTP dengan alasan ada 'transaksi mencurigakan'.</p>
        <div class="bg-red-50 border border-red-200 rounded-xl p-3 text-sm"><strong class="text-red-800">Ingat:</strong> <span class="text-red-700">Tidak ada pihak resmi manapun yang meminta OTP lewat telepon atau SMS!</span></div>
    </div>
