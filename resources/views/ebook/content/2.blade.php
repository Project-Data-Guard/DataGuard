    <div class="overflow-x-auto mb-6">
        <table class="w-full border-collapse rounded-xl overflow-hidden text-sm">
            <thead><tr class="bg-red-800 text-white"><th class="p-3 text-left">Istilah</th><th class="p-3 text-left">Definisi</th><th class="p-3 text-left">Analogi</th></tr></thead>
            <tbody>
                <tr class="bg-red-50 border-b"><td class="p-3 font-semibold">Phishing</td><td class="p-3">Penipuan digital menggunakan umpan yang tampak sah (email, SMS, link, situs palsu) untuk mencuri data atau uang.</td><td class="p-3 italic text-gray-500">Seperti memancing ikan dengan umpan, tapi yang dipancing adalah datamu.</td></tr>
                <tr class="bg-white"><td class="p-3 font-semibold">Social Engineering</td><td class="p-3">Manipulasi psikologis lewat interaksi manusia agar korban secara sukarela memberikan informasi atau melakukan sesuatu.</td><td class="p-3 italic text-gray-500">Seperti penipu yang berpura-pura jadi teman untuk mendapatkan kepercayaanmu.</td></tr>
